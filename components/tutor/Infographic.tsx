'use client';

import React, { useState } from 'react';
import {
  Lightbulb, Wrench, FileText, Settings, Type, List, Star, Zap, BarChart,
  Brain, Heart, Layers, Search, Shield, Globe, Database, Code, Users, Target,
  BookOpen, Cpu, Eye, Lock, Trash2, RefreshCw, ArrowRight, ChevronLeft,
  ChevronRight, Sparkles, ArrowRightLeft, CheckCircle
} from 'lucide-react';

/* ─── Icon Mapping ───────────────────────────────────────────── */
const getIcon = (concept: string, size = 28) => {
  const c = (concept || '').toLowerCase();
  const p = { size, strokeWidth: 2 };
  if (c.includes('idea') || c.includes('light')) return <Lightbulb {...p} />;
  if (c.includes('tool') || c.includes('wrench') || c.includes('clean')) return <Wrench {...p} />;
  if (c.includes('file') || c.includes('doc')) return <FileText {...p} />;
  if (c.includes('set') || c.includes('config') || c.includes('gear')) return <Settings {...p} />;
  if (c.includes('text') || c.includes('type') || c.includes('write')) return <Type {...p} />;
  if (c.includes('list')) return <List {...p} />;
  if (c.includes('star') || c.includes('best')) return <Star {...p} />;
  if (c.includes('fast') || c.includes('quick') || c.includes('zap') || c.includes('power')) return <Zap {...p} />;
  if (c.includes('chart') || c.includes('graph') || c.includes('data')) return <BarChart {...p} />;
  if (c.includes('brain') || c.includes('mind') || c.includes('ai') || c.includes('think')) return <Brain {...p} />;
  if (c.includes('heart') || c.includes('love')) return <Heart {...p} />;
  if (c.includes('layer') || c.includes('stack')) return <Layers {...p} />;
  if (c.includes('search') || c.includes('find') || c.includes('seo')) return <Search {...p} />;
  if (c.includes('shield') || c.includes('secure') || c.includes('safe')) return <Shield {...p} />;
  if (c.includes('globe') || c.includes('web') || c.includes('world')) return <Globe {...p} />;
  if (c.includes('database') || c.includes('store') || c.includes('server')) return <Database {...p} />;
  if (c.includes('code') || c.includes('dev')) return <Code {...p} />;
  if (c.includes('user') || c.includes('people') || c.includes('team')) return <Users {...p} />;
  if (c.includes('target') || c.includes('goal')) return <Target {...p} />;
  if (c.includes('book') || c.includes('learn') || c.includes('read')) return <BookOpen {...p} />;
  if (c.includes('cpu') || c.includes('process') || c.includes('compute')) return <Cpu {...p} />;
  if (c.includes('eye') || c.includes('view') || c.includes('vision')) return <Eye {...p} />;
  if (c.includes('lock') || c.includes('private')) return <Lock {...p} />;
  if (c.includes('trash') || c.includes('delete') || c.includes('remove')) return <Trash2 {...p} />;
  if (c.includes('refresh') || c.includes('sync') || c.includes('update')) return <RefreshCw {...p} />;
  return <Target {...p} />;
};

