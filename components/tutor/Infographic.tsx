/* ═══════════════════════════════════════════════════════════════
   MAIN COMPONENT
   ═══════════════════════════════════════════════════════════════ */
export function Infographic({ data }: { data: any }) {
  const [currentSlide, setCurrentSlide] = useState(0);

  /* ─── Normalize ────────────────────────────────── */
  let parsed = { main_title: '', subtitle: '', golden_rule: '', slides: [] as any[] };

  if (Array.isArray(data)) {
    parsed.slides = data.map((s: any) => ({
      slide_type: 'concept', title: s.title || s.key_point || '', icon_concept: s.icon_concept || 'target',
      description: s.description || s.details || '', key_points: s.tags || [],
    }));
    parsed.main_title = 'Generated Infographic';
  } else if (data && typeof data === 'object') {
    parsed.main_title = data.main_title || 'Infographic';
    parsed.subtitle = data.subtitle || '';
    parsed.golden_rule = data.golden_rule || '';
    parsed.slides = Array.isArray(data.slides) ? data.slides
      : Array.isArray(data.sections) ? data.sections.map((s: any) => ({
        slide_type: 'concept', title: s.title || '', icon_concept: s.icon_concept || 'target',
        description: s.description || '', key_points: s.tags || [],
      })) : [];
  }

  const hasGolden = !!parsed.golden_rule;
  const total = 1 + parsed.slides.length + (hasGolden ? 1 : 0);

  const goNext = () => setCurrentSlide(p => Math.min(p + 1, total - 1));
  const goPrev = () => setCurrentSlide(p => Math.max(p - 1, 0));

  const renderSlide = () => {
    if (currentSlide === 0) return <TitleSlide title={parsed.main_title} subtitle={parsed.subtitle} totalSlides={total} />;
    if (hasGolden && currentSlide === total - 1) return <GoldenRuleSlide goldenRule={parsed.golden_rule} />;

    const idx = currentSlide - 1;
    const sl = parsed.slides[idx];
    if (!sl) return null;
    switch (sl.slide_type) {
      case 'comparison': return <ComparisonSlide slide={sl} index={idx} goldenRule={parsed.golden_rule} />;
      case 'list': return <ListSlide slide={sl} index={idx} />;
      case 'process': return <ProcessSlide slide={sl} index={idx} />;
      default: return <ConceptSlide slide={sl} index={idx} />;
    }
  };

  return (
    <div className="w-full max-w-5xl mx-auto rounded-2xl overflow-hidden" data-infographic-total={total} style={{ boxShadow: '0 12px 40px rgba(0,0,0,0.12)' }}>

      {/* Current Slide */}
      <div data-infographic-slide>
        {renderSlide()}
      </div>

      {/* Navigation */}
      <div className="flex items-center justify-between px-5 py-3" style={{ background: '#fff', borderTop: '1px solid #e5ebe6' }}>
        <button onClick={goPrev} disabled={currentSlide === 0}
          className="flex items-center gap-1.5 px-4 py-2 rounded-lg text-sm font-semibold transition-all disabled:opacity-25"
          style={{ background: '#eaf2eb', color: '#1a3821' }}>
          <ChevronLeft size={16} /> Prev
        </button>

        {/* Dots */}
        <div className="flex items-center gap-1.5 flex-wrap justify-center">
          {Array.from({ length: total }).map((_, i) => (
            <button key={i} data-infographic-dot onClick={() => setCurrentSlide(i)}
              className="rounded-full transition-all"
              style={{
                width: i === currentSlide ? 24 : 10, height: 10,
                background: i === currentSlide ? '#1a3821' : '#c5d8c7',
              }} />
          ))}
        </div>

        <button onClick={goNext} disabled={currentSlide === total - 1}
          className="flex items-center gap-1.5 px-4 py-2 rounded-lg text-sm font-semibold text-white transition-all disabled:opacity-25"
          style={{ background: '#1a3821' }}>
          Next <ChevronRight size={16} />
        </button>
      </div>
    </div>
  );
}
